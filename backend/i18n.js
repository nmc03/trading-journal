const DEFAULT_LANG = "es";
const LANGS = Object.keys(MESSAGES);

// req.acceptsLanguages returns the best match among LANGS (the first one when there is no header).
function pickLang(req) {
  return req?.acceptsLanguages?.(...LANGS) || DEFAULT_LANG;
}

function translate(lang, code, params = {}) {
  const dict = MESSAGES[lang] || MESSAGES[DEFAULT_LANG];
  const template = dict[code] ?? MESSAGES[DEFAULT_LANG][code] ?? code;
  return template.replace(/\{(\w+)\}/g, (_, key) => {
    if (key === "field") return dict[`field.${params.field}`] ?? MESSAGES[DEFAULT_LANG][`field.${params.field}`] ?? params.field;
    return params[key] ?? "";
  });
}

module.exports = { MESSAGES, LANGS, DEFAULT_LANG, pickLang, translate };
